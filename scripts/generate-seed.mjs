// Generates supabase/seed.sql from content/challenges.json.
// Usage: node scripts/generate-seed.mjs [start-date]
// Example: node scripts/generate-seed.mjs 2026-11-01
// Each challenge gets the next day's publish_date, starting at start-date (default: today, America/New_York).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const challenges = JSON.parse(readFileSync(join(root, "content/challenges.json"), "utf8"));

const today = new Intl.DateTimeFormat("en-CA", { timeZone: "America/New_York" }).format(new Date());
const start = process.argv[2] ?? today;
if (!/^\d{4}-\d{2}-\d{2}$/.test(start)) {
  console.error("Start date must look like YYYY-MM-DD");
  process.exit(1);
}

// Dollar quoting avoids escaping quotes in logs and emails.
const q = (s) => {
  let tag = "$c$";
  let n = 0;
  while (String(s).includes(tag)) tag = `$c${++n}$`;
  return `${tag}${s}${tag}`;
};

const addDays = (iso, days) => {
  const d = new Date(`${iso}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
};

let sql = `-- Generated by scripts/generate-seed.mjs on ${new Date().toISOString()}\n`;
sql += `-- Start date: ${start}. Safe to re-run: existing slugs are updated in place.\n\n`;

challenges.forEach((c, i) => {
  const date = addDays(start, i);
  sql += `-- ${date}: ${c.title}\n`;
  sql += `with ch as (
  insert into public.challenges (publish_date, slug, title, category, difficulty, scenario, artifact, artifact_type, question, choices)
  values ('${date}', ${q(c.slug)}, ${q(c.title)}, ${q(c.category)}, ${c.difficulty}, ${q(c.scenario)}, ${q(c.artifact)}, ${q(c.artifact_type)}, ${q(c.question)}, ${q(JSON.stringify(c.choices))}::jsonb)
  on conflict (slug) do update set
    publish_date = excluded.publish_date, title = excluded.title, category = excluded.category,
    difficulty = excluded.difficulty, scenario = excluded.scenario, artifact = excluded.artifact,
    artifact_type = excluded.artifact_type, question = excluded.question, choices = excluded.choices
  returning id
)
insert into public.challenge_answers (challenge_id, correct_index, explanation, attack_technique)
select id, ${c.correct_index}, ${q(c.explanation)}, ${c.attack_technique ? q(c.attack_technique) : "null"} from ch
on conflict (challenge_id) do update set
  correct_index = excluded.correct_index, explanation = excluded.explanation, attack_technique = excluded.attack_technique;

`;
});

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`Wrote ${challenges.length} challenges to supabase/seed.sql (${start} to ${addDays(start, challenges.length - 1)})`);
